-- COUNT()

SELECT COUNT(*) -- How many employees do we have?
FROM employees;

-- MAX()

SELECT MAX(Sales) -- What is the highest sales  value?
FROM employees;

-- MIN()

SELECT MIN(Sales) -- What is the lowest sales value?
FROM employees;

-- AVG()

SELECT AVG(Sales) -- What is the average sales amount?
FROM employees;

-- SUM()

SELECT SUM(Sales) -- What are the total company sales?
FROM employees;


